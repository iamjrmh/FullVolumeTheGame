#!/usr/bin/env node
// Writes docs/changelog/releases.js from the GitHub releases API.
//
// The changelog page is live: it asks /api/releases on load, so a release
// published a minute ago is on the site a minute ago with nothing rebuilt. This
// is the copy it paints first, before the network has answered, and the copy it
// keeps if the function is cold, the API is rate limited, or the page was opened
// straight off disk. Same parser as the function, imported from the same file,
// so the two can never disagree about what a release said.
//
// A script rather than JSON, matching data/vocals.js and data/rb3.js, because
// fetch() is blocked on file:// and the page still has to fill in there.
//
//   node tools/bake-changelog.mjs           write it
//   node tools/bake-changelog.mjs --check   report drift, exit 1, write nothing
//   node tools/bake-changelog.mjs --print   dump the parse and write nothing
//   node tools/bake-changelog.mjs --soft    write it, but never fail: if GitHub
//                                           cannot be reached, keep the copy
//                                           already in docs/ and exit 0. This
//                                           is what the Netlify build runs, so
//                                           a rate limit costs freshness, not
//                                           the deploy.

import { writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { fetchReleases, buildChangelog, REPO } from "../netlify/lib/releasenotes.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
// Next to the page, not under docs/data/: robots.txt disallows /data/ for the
// chart catalogues, and Googlebot has to be able to fetch this one to see the
// notes at all.
const OUT = join(ROOT, "docs", "changelog", "releases.js");

/** The generated stamp moves on every run; the notes are what actually changed. */
const fingerprint = (doc) => JSON.stringify({ ...doc, generated: null });

function render(doc) {
  return `/* FullVolume release notes, read off the GitHub releases API.
   Generated by tools/bake-changelog.mjs - do not edit by hand.

   This is the copy /changelog/ paints before the network answers. The live one
   comes from /api/releases a moment later; if it has moved on, the page swaps
   to it. Re-bake with: node tools/bake-changelog.mjs
*/
window.FV_CHANGELOG = ${JSON.stringify(doc, null, 1)};
`;
}

async function main() {
  const check = process.argv.includes("--check");
  const print = process.argv.includes("--print");
  const soft = process.argv.includes("--soft");

  let doc;
  try {
    const raw = await fetchReleases({ token: process.env.GITHUB_TOKEN || "" });
    doc = buildChangelog(raw, { repo: REPO });
    if (!doc.releases.length) throw new Error("no releases came back");
  } catch (err) {
    const have = await readFile(OUT, "utf8").catch(() => "");
    if (soft && have) {
      console.warn(`Could not read the releases (${err.message}); keeping the copy already in docs/.`);
      return 0;
    }
    console.error(`Could not read the releases: ${err.message}. Refusing to write an empty changelog.`);
    return 1;
  }

  console.log(`${doc.releases.length} releases, latest v${doc.latest}`);
  for (const r of doc.releases) {
    const items = r.sections.reduce((n, s) => n + s.blocks.filter((b) => b.type === "item").length, 0);
    console.log(
      `  ${r.tag.padEnd(8)} ${r.date}  ${String(r.sections.length).padStart(2)} section(s), ` +
      `${String(items).padStart(2)} change(s), ${r.assets.length} installer(s)`
    );
    for (const s of r.sections) console.log(`             - ${s.kind}: ${s.title}`);
  }

  if (print) {
    console.log(JSON.stringify(doc, null, 2));
    return 0;
  }

  const next = render(doc);
  const current = await readFile(OUT, "utf8").catch(() => "");

  if (current) {
    const was = current.match(/window\.FV_CHANGELOG = ([\s\S]*);\n$/);
    if (was && fingerprint(JSON.parse(was[1])) === fingerprint(doc)) {
      console.log("Already current - only the generated stamp would move, so leaving it alone.");
      return 0;
    }
  }

  if (check) {
    console.error("\ndocs/changelog/releases.js is behind the releases API. Run: node tools/bake-changelog.mjs");
    return 1;
  }

  await writeFile(OUT, next, "utf8");
  console.log(`\nWrote ${OUT}`);
  return 0;
}

// Not process.exit(): on Windows that races the closing fetch socket and libuv
// asserts on the way out. Setting the code lets the loop drain first.
process.exitCode = await main();
